-- issue.lua 의 짝. 발급 자격을 얻은 뒤 그 발급이 끝내 성사되지 못했을 때 되돌린다.
-- (지금 부르는 곳: 큐에 넣는 것이 실패했을 때 — CouponService.issue)
--
-- 되돌리지 않으면 그 한 장은 아무에게도 가지 않은 채 사라지고(과소발급),
-- 사용자는 users 집합에 남아 다시 시도해도 영영 거절된다.
-- DB 안에는 아무 모순이 없어 verify 의 세 판정은 전부 OK 로 통과한다.
--
-- KEYS[1] = coupon:{id}:stock   (재고 카운터)
-- KEYS[2] = coupon:{id}:users   (발급된 사용자 set)
-- ARGV[1] = user_id
-- 반환:
--   1   되돌렸다
--   0   되돌릴 것이 없다 (이미 되돌렸거나 애초에 발급되지 않았다)
--
-- SREM 이 실제로 하나를 지웠을 때만 INCR 한다는 것이 핵심이다.
-- 두 번 불려도 재고가 두 번 늘지 않는다(멱등). 프로듀서 콜백은 중복 호출을 보장하지 않으므로
-- 이 성질이 없으면 보상이 과발급을 만든다.
--
-- 차감(DECR + SADD)과 마찬가지로 복구(SREM + INCR)도 두 명령이다. 따로 보내면 그 사이에서
-- 죽었을 때 재고는 돌아왔는데 사용자는 막힌 채로 남는다. issue.lua 와 같은 이유로 한 덩어리다.

if redis.call('SREM', KEYS[2], ARGV[1]) == 1 then
  redis.call('INCR', KEYS[1])
  return 1
end
return 0
